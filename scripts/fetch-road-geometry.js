// One-time / re-runnable data-generation script: fetches real road-following
// geometry for every corridor leg (lib/corridors.ts) from the public OSRM
// demo routing server, and writes lib/corridorPaths.ts.
//
// This is NOT part of the running app — the app never calls a routing API
// at runtime, only reads the generated static file. Re-run this manually
// (`node scripts/fetch-road-geometry.js`) whenever stop coordinates in
// corridors.ts change.
//
// OSRM's default profile optimizes for driving *time*, not distance, so on
// a small fraction of legs (Jakarta's toll roads / one-way systems) the
// "fastest" route is a large geographic detour that doesn't reflect the
// real bus corridor shape at all. Any leg whose road distance exceeds the
// straight-line distance by more than MAX_EXCESS_KM falls back to a
// straight line for that leg only (same as when OSRM finds no route).
const fs = require("fs");
const path = require("path");

const PROJECT_DIR = path.join(__dirname, "..");
const CORRIDORS_TS = path.join(PROJECT_DIR, "lib", "corridors.ts");
const OUT_TS = path.join(PROJECT_DIR, "lib", "corridorPaths.ts");
const MAX_EXCESS_KM = 2.5;
const REQUEST_DELAY_MS = 120; // be polite to the shared public demo server

function parseCorridors(src) {
  const blocks = src.split(/\n  \{\n?    id: /).slice(1);
  const corridors = [];
  for (const b of blocks) {
    const idMatch = b.match(/^"([a-z0-9]+)"/);
    if (!idMatch) continue;
    const id = idMatch[1];
    const stopsSection = b.match(/stops:\s*\[([\s\S]*?)\n\s*\],/);
    if (!stopsSection) continue;
    const stopMatches = [...stopsSection[1].matchAll(/\{ n: "([^"]+)", lat: (-?\d+\.\d+), lng: (-?\d+\.\d+) \}/g)];
    const stops = stopMatches.map((m) => ({ n: m[1], lat: +m[2], lng: +m[3] }));
    if (stops.length >= 2) corridors.push({ id, stops });
  }
  return corridors;
}

function haversineKm(a, b) {
  const R = 6371;
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const s = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

async function fetchLeg(a, b) {
  const url = `https://router.project-osrm.org/route/v1/driving/${a.lng},${a.lat};${b.lng},${b.lat}?overview=full&geometries=geojson`;
  const res = await fetch(url);
  const json = await res.json();
  if (json.code !== "Ok" || !json.routes?.[0]) throw new Error(json.code || "no route");
  return json.routes[0].geometry.coordinates.map(([lng, lat]) => ({ lat, lng }));
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

async function main() {
  const src = fs.readFileSync(CORRIDORS_TS, "utf8");
  const corridors = parseCorridors(src);
  console.log(`Parsed ${corridors.length} corridors`);

  const result = {};
  for (const c of corridors) {
    console.log(`Fetching ${c.id} (${c.stops.length} stops, ${c.stops.length - 1} legs)...`);
    const points = [{ lat: c.stops[0].lat, lng: c.stops[0].lng }];
    const breaks = [0];
    for (let i = 0; i < c.stops.length - 1; i++) {
      const a = c.stops[i];
      const b = c.stops[i + 1];
      const straightKm = haversineKm(a, b);
      let legPts;
      try {
        legPts = await fetchLeg(a, b);
      } catch (e) {
        console.warn(`  ${a.n} -> ${b.n}: OSRM failed (${e.message}), using straight line`);
        legPts = [a, b];
      }
      let roadKm = 0;
      for (let k = 0; k < legPts.length - 1; k++) roadKm += haversineKm(legPts[k], legPts[k + 1]);
      if (roadKm - straightKm > MAX_EXCESS_KM) {
        console.warn(`  ${a.n} -> ${b.n}: road ${roadKm.toFixed(2)}km vs straight ${straightKm.toFixed(2)}km, unrealistic detour -> using straight line`);
        legPts = [a, b];
      }
      for (let j = 1; j < legPts.length; j++) points.push({ lat: legPts[j].lat, lng: legPts[j].lng });
      breaks.push(points.length - 1);
      await sleep(REQUEST_DELAY_MS);
    }
    const forwardPoints = points;
    const forwardBreaks = breaks;
    const backwardPoints = [...forwardPoints].reverse();
    const n = forwardPoints.length - 1;
    const backwardBreaks = [...forwardBreaks].reverse().map((b) => n - b);
    result[c.id] = {
      forward: { points: forwardPoints, breaks: forwardBreaks },
      backward: { points: backwardPoints, breaks: backwardBreaks },
    };
    const totalKm = forwardPoints.reduce((sum, p, i) => (i === 0 ? 0 : sum + haversineKm(forwardPoints[i - 1], p)), 0);
    console.log(`  -> ${forwardPoints.length} pts, ${totalKm.toFixed(2)} km`);
  }

  const lines = [];
  lines.push("// AUTO-GENERATED by scripts/fetch-road-geometry.js using the public OSRM demo");
  lines.push("// routing server (router.project-osrm.org) — a one-time offline data-generation");
  lines.push("// step, NOT a runtime dependency. The app never calls any routing API while");
  lines.push("// running. Regenerate by re-running that script if stop coordinates in");
  lines.push("// corridors.ts change. Geometry follows OSM's general road network (fastest car");
  lines.push("// route), not verified official Transjakarta bus-lane centerlines. A leg falls");
  lines.push("// back to a straight line where OSRM found no route, or where its \"fastest\"");
  lines.push(`// route detoured more than ${MAX_EXCESS_KM}km past the straight-line distance (e.g. via a`);
  lines.push("// toll-road loop) — such detours don't reflect the real bus corridor shape.");
  lines.push('export interface RoadPoint { lat: number; lng: number }');
  lines.push('export interface DirectionalPath { points: RoadPoint[]; breaks: number[] }');
  lines.push('export interface CorridorPath { forward: DirectionalPath; backward: DirectionalPath }');
  lines.push("");
  lines.push("export const CORRIDOR_PATHS: Record<string, CorridorPath> = {");
  for (const [id, cp] of Object.entries(result)) {
    lines.push(`  ${id}: {`);
    for (const dir of ["forward", "backward"]) {
      const pts = cp[dir].points.map((p) => `[${p.lat},${p.lng}]`).join(",");
      lines.push(`    ${dir}: { breaks: [${cp[dir].breaks.join(",")}], points: [${pts}].map(([lat,lng])=>({lat,lng})) },`);
    }
    lines.push("  },");
  }
  lines.push("};");

  fs.writeFileSync(OUT_TS, lines.join("\n") + "\n", "utf8");
  console.log(`\nWrote ${OUT_TS}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
